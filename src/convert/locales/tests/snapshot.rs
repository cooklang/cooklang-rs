//! An exhaustive, machine-oriented snapshot of everything the naming and
//! preference layers decide, so that they can be refactored without the
//! data changing by accident. `docs/units.md` (rendered at the foot of this
//! file) is the page a person reads; these files are the decisions.
//!
//! `snapshots/locales.snapshot` holds every decision, locale by locale and
//! then what belongs to no single locale; `snapshots/<tag>.md` pins a few
//! `show-locale-as-md` pages. The test fails when a committed copy differs or
//! a file is left behind that is no longer generated; `UPDATE_UNITS_DOC=1
//! cargo test` rewrites them, and the diff is the review.
//!
//! What a rule implies is not repeated here: an identifier resolving to itself, a universal alias, an unnamed unit
//! written by its identifier. Each such rule has a unit test in `tests/mod.rs`, and pinning its consequences per
//! locale would only multiply the diff when the rule changed.

use std::collections::HashSet;
use std::fmt::Write;

use icu_locale_core::subtags::{region, Region};

use crate::convert::locales::legacy::{legacy_locale, LEGACY_PREFERENCES};
use crate::convert::locales::locale::Locale;
use crate::convert::locales::preference::{
    best_amount, best_unit, official_system, Audience, Row, System, Units, PREFERENCES,
    REGION_PREFERENCES,
};
use crate::convert::locales::reference;
use crate::convert::locales::tag::LocaleTag;
use crate::convert::locales::vendored::{tag_for, vendored_locale, vendored_tags, PARENT_LOCALES};
use crate::convert::units::{PhysicalQuantity, TemperatureUnit, Unit};

const DIR: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/src/convert/locales/tests/snapshots"
);

const HEADER: &str = "# Generated by src/convert/locales/tests/snapshot.rs. Do not edit: run\n\
                      # UPDATE_UNITS_DOC=1 cargo test to refresh. Every line is a decision\n\
                      # the naming or preference layer makes; a diff here is a behaviour\n\
                      # change.\n";

const MARKDOWN_HEADER: &str =
    "<!-- Generated by src/convert/locales/tests/snapshot.rs. Do not edit: \
                               run UPDATE_UNITS_DOC=1 cargo test to refresh. -->\n\n";

/// Tags whose `show-locale-as-md` page is pinned, one for each kind of page:
/// legacy, a language with no region, a regional tag whose names come from its
/// parent, a region with rows of its own, a US reader, a metric region, a
/// system asked for with `-u-ms-` and a temperature unit asked for with
/// `-u-mu-`.
const MARKDOWN_TAGS: [&str; 8] = [
    "legacy",
    "pl",
    "en-NZ",
    "sv-SE",
    "es-US",
    "en-GB",
    "en-GB-u-ms-uksystem",
    "en-CA-u-mu-fahrenhe",
];

/// Regions whose official system is worth pinning: the one exception, the
/// territories CLDR files under other systems, and a spread of metric ones.
const REGIONS: [Region; 12] = [
    region!("US"),
    region!("GB"),
    region!("LR"),
    region!("MM"),
    region!("001"),
    region!("AU"),
    region!("CA"),
    region!("DE"),
    region!("FR"),
    region!("IN"),
    region!("JP"),
    region!("MX"),
];

const VALUES: [f64; 6] = [0.5, 1.0, 2.5, 100.0, 1000.0, -18.0];

/// Amounts that exercise the fraction rows: a third, a half, three quarters,
/// a near-whole, wholes, and odd amounts that fit no fraction of the first
/// unit they reach.
const AMOUNT_VALUES: [f64; 8] = [0.3, 0.5, 0.75, 1.1, 3.0, 7.0, 100.0, 2500.0];
const AMOUNT_UNITS: [&str; 6] = [
    "milliliter",
    "gram",
    "us cup",
    "us teaspoon",
    "imperial pint",
    "celsius",
];

const AUDIENCES: [Audience; 7] = [
    Audience::system(System::Metric),
    Audience::system(System::UsCustomary),
    Audience::system(System::Imperial),
    Audience::region(region!("US")),
    Audience::region(region!("GB")),
    Audience::legacy(System::Metric),
    Audience::legacy(System::UsCustomary),
];

/// The three systems, two plain regions, and every region with rows of its
/// own, so a new region row is pinned the day it is added.
fn audiences() -> Vec<Audience> {
    let mut audiences: Vec<Audience> = AUDIENCES.to_vec();
    for (region, _, _) in REGION_PREFERENCES {
        let audience = Audience::region(*region);
        if !audiences.contains(&audience) {
            audiences.push(audience);
        }
    }
    audiences
}

fn fractions_suffix(row: &Row) -> String {
    let fractions = match row.fractions {
        Some(den) => format!(" fractions /{den}"),
        None => String::new(),
    };
    if row.or_decimal {
        format!("{fractions} or decimal")
    } else {
        fractions
    }
}

fn audience_name(audience: Audience) -> String {
    let units = match audience.units {
        Units::System(system) => format!("system:{system:?}"),
        Units::Region(region) => format!("region:{region}"),
        Units::Legacy(system) => format!("legacy:{system:?}"),
    };
    match audience.temperature {
        Some(unit) => format!("{units}+mu:{unit:?}"),
        None => units,
    }
}

fn render_decisions(out: &mut String, tag: &str, locale: &Locale) {
    let mut inputs: Vec<(String, &'static str)> = Unit::all()
        .flat_map(|unit| {
            locale
                .names(unit)
                .into_iter()
                .flat_map(|names| names.symbol.iter().chain(&names.aliases).cloned())
                .map(move |s| (s, unit.id()))
        })
        .collect();
    inputs.sort();
    inputs.dedup();
    for (input, id) in inputs {
        assert_eq!(locale.resolve(&input), Unit::from_id(id), "{tag} '{input}'");
        writeln!(out, "resolve {tag} {input:?} -> {id}").unwrap();
    }
    for unit in Unit::all() {
        writeln!(
            out,
            "written {tag} {} -> {:?}",
            unit.id(),
            locale.written(unit)
        )
        .unwrap();
    }
    // 0, 12 and 14 are where Finnish and Polish leave the obvious category
    for unit in Unit::all() {
        let Some(names) = locale.names(unit) else {
            continue;
        };
        for (category, pattern) in &names.long {
            writeln!(out, "long {tag} {} {category} -> {pattern:?}", unit.id()).unwrap();
        }
        if !names.long.is_empty() {
            for value in [1.0, 2.0, 5.0, 22.0, 1.5, 0.0, 12.0, 14.0] {
                writeln!(
                    out,
                    "long-written {tag} {} {value} -> {:?}",
                    unit.id(),
                    locale.written_long(value, unit)
                )
                .unwrap();
            }
        }
    }
}

/// The snapshot files as `(file name, contents)`.
///
/// Every locale is here, reviewed or not, so that a name cannot drift before
/// someone reviews the locale and confirms the drifted name as CLDR's.
pub(crate) fn files() -> Vec<(String, String)> {
    let mut out = String::from(HEADER);
    render_decisions(&mut out, "legacy", &legacy_locale());
    let mut tags: Vec<&str> = vendored_tags().collect();
    tags.sort_unstable();
    for tag in &tags {
        render_decisions(&mut out, tag, &vendored_locale(tag).expect("vendored"));
    }
    render_derived(&mut out, &tags);

    let mut files = vec![("locales.snapshot".to_string(), out)];
    for tag in MARKDOWN_TAGS {
        let page = reference::render_locale(tag).expect("a renderable tag");
        files.push((format!("{tag}.md"), format!("{MARKDOWN_HEADER}{page}")));
    }
    files
}

/// What is keyed by tag, region or system rather than by a language's names,
/// and so belongs to no single locale.
fn render_derived(out: &mut String, tags: &[&str]) {
    let mut probes: Vec<String> = tags.iter().map(|t| (*t).to_string()).collect();
    probes.extend(PARENT_LOCALES.iter().map(|(child, _)| child.to_string()));
    probes.extend(
        [
            "en-US",
            "de-AT",
            "de-CH",
            "fr-CA",
            "fr-FR",
            "sv-FI",
            "zh-Hans-CN",
            "und",
            "sw-KE",
        ]
        .map(str::to_string),
    );
    probes.sort();
    probes.dedup();
    for probe in probes {
        let reached = LocaleTag::parse(&probe)
            .ok()
            .and_then(|tag| tag_for(&tag))
            .unwrap_or("none");
        writeln!(out, "fallback {probe} -> {reached}").unwrap();
    }

    for region in REGIONS {
        writeln!(
            out,
            "official-system {region} -> {:?}",
            official_system(region)
        )
        .unwrap();
    }
    for (system, quantity, rows) in PREFERENCES {
        for row in rows.iter() {
            writeln!(
                out,
                "preference {system:?} {quantity:?} {} >= {}{}",
                row.unit.id(),
                row.at_least,
                fractions_suffix(row)
            )
            .unwrap();
        }
    }
    for (region, quantity, rows) in REGION_PREFERENCES {
        for row in rows.iter() {
            writeln!(
                out,
                "preference region:{region} {quantity:?} {} >= {}{}",
                row.unit.id(),
                row.at_least,
                fractions_suffix(row)
            )
            .unwrap();
        }
    }
    for (system, quantity, rows) in LEGACY_PREFERENCES {
        for row in rows.iter() {
            writeln!(
                out,
                "preference legacy:{system:?} {quantity:?} {} >= {}{}",
                row.unit.id(),
                row.at_least,
                fractions_suffix(row)
            )
            .unwrap();
        }
    }
    for audience in audiences() {
        for unit in Unit::all() {
            for value in VALUES {
                let chosen = best_unit(value, unit, audience);
                writeln!(
                    out,
                    "best {} {value} {} -> {}",
                    audience_name(audience),
                    unit.id(),
                    chosen.id()
                )
                .unwrap();
            }
        }
    }
    // what is written, fraction and unit together, for the amounts that
    // exercise the fraction rows
    let amount_units = AMOUNT_UNITS.map(|id| Unit::from_id(id).expect("a unit"));
    for audience in audiences() {
        for unit in amount_units {
            for value in AMOUNT_VALUES {
                let (amount, chosen) = best_amount(value, unit, audience);
                writeln!(
                    out,
                    "amount {} {value} {} -> {amount} {}",
                    audience_name(audience),
                    unit.id(),
                    chosen.id()
                )
                .unwrap();
            }
        }
    }
    // `-u-mu-` overrides temperature only: both directions, with a volume
    // and a mass unit as witnesses that nothing else moves
    let overrides = [
        Audience::region(region!("CA")).with_temperature(TemperatureUnit::Fahrenheit),
        Audience::system(System::UsCustomary).with_temperature(TemperatureUnit::Celsius),
    ];
    let witnesses = ["celsius", "fahrenheit", "milliliter", "gram"]
        .map(|id| Unit::from_id(id).expect("a unit"));
    for audience in overrides {
        for unit in witnesses {
            for value in VALUES {
                let chosen = best_unit(value, unit, audience);
                writeln!(
                    out,
                    "best {} {value} {} -> {}",
                    audience_name(audience),
                    unit.id(),
                    chosen.id()
                )
                .unwrap();
            }
        }
    }
}

/// Every unit a preference row can choose is chosen somewhere in the grid.
///
/// Rows are read largest-first and the first whose threshold is met wins, so
/// a row placed below one that always wins is dead; this is what catches it.
/// A unit in no row is unreachable by construction, so adding samples cannot
/// "reach" one -- the lever is the row, not the value.
#[test]
fn the_samples_reach_every_unit_a_row_can_choose() {
    let mut reachable: HashSet<Unit> = HashSet::new();
    for (_, _, rows) in PREFERENCES {
        reachable.extend(rows.iter().map(|row| row.unit));
    }
    for (_, _, rows) in REGION_PREFERENCES {
        reachable.extend(rows.iter().map(|row| row.unit));
    }
    for (_, _, rows) in LEGACY_PREFERENCES {
        reachable.extend(rows.iter().map(|row| row.unit));
    }

    let mut chosen: HashSet<Unit> = HashSet::new();
    for audience in audiences() {
        for unit in Unit::all() {
            for value in VALUES {
                chosen.insert(best_unit(value, unit, audience));
            }
        }
    }

    let unreached: Vec<&str> = {
        let mut v: Vec<&str> = reachable.difference(&chosen).map(|u| u.id()).collect();
        v.sort_unstable();
        v
    };
    assert!(
        unreached.is_empty(),
        "a preference row can choose these and no sample does, so the grid \
         never exercises them: {unreached:?}. Add a value to VALUES in the \
         band the row covers."
    );
}

#[test]
fn the_committed_snapshots_are_current() {
    let files = files();

    if std::env::var_os("UPDATE_UNITS_DOC").is_some() {
        std::fs::create_dir_all(DIR).expect("writable");
        for (name, body) in &files {
            std::fs::write(format!("{DIR}/{name}"), body).expect("writable");
        }
        // a locale dropped from the vendored set must take its file with it,
        // or a stale one lingers looking current
        for entry in std::fs::read_dir(DIR).expect("readable") {
            let name = entry.unwrap().file_name().to_string_lossy().to_string();
            if !files.iter().any(|(n, _)| *n == name) {
                std::fs::remove_file(format!("{DIR}/{name}")).expect("removable");
            }
        }
        return;
    }

    let mut stale = Vec::new();
    for (name, body) in &files {
        let committed = std::fs::read_to_string(format!("{DIR}/{name}")).unwrap_or_default();
        if &committed != body {
            // a full assert_eq! would print two multi-hundred-line strings
            let where_ = committed
                .lines()
                .zip(body.lines())
                .position(|(a, b)| a != b)
                .map(|i| format!("line {}", i + 1))
                .unwrap_or_else(|| "length".to_string());
            stale.push(format!("{name} ({where_})"));
        }
    }
    let extra: Vec<String> = std::fs::read_dir(DIR)
        .map(|dir| {
            dir.filter_map(|e| {
                let name = e.ok()?.file_name().to_string_lossy().to_string();
                (!files.iter().any(|(n, _)| *n == name)).then_some(name)
            })
            .collect()
        })
        .unwrap_or_default();

    assert!(
        stale.is_empty() && extra.is_empty(),
        "src/convert/locales/tests/snapshots is stale; rerun with UPDATE_UNITS_DOC=1\n  \
         differs: {}\n  not generated any more: {}",
        if stale.is_empty() {
            "-".to_string()
        } else {
            stale.join(", ")
        },
        if extra.is_empty() {
            "-".to_string()
        } else {
            extra.join(", ")
        },
    );
}

/// The unit each quantity's factors are expressed against.
fn reference_unit(quantity: PhysicalQuantity) -> Unit {
    let id = match quantity {
        PhysicalQuantity::Volume => "liter",
        PhysicalQuantity::Mass => "gram",
        PhysicalQuantity::Length => "meter",
        PhysicalQuantity::Time => "second",
        PhysicalQuantity::Temperature => "celsius",
    };
    Unit::from_id(id).expect("a reference unit")
}

/// `docs/units.md`: every unit and every preference row, as a page a person
/// reads.
fn render_units_doc() -> String {
    let mut out = String::new();
    out.push_str("# Units\n\n");
    out.push_str(
        "Generated from the unit definitions and the preference rows. **Do not edit**: run\n",
    );
    out.push_str("`UPDATE_UNITS_DOC=1 cargo test` to refresh it.\n\n");
    out.push_str(
        "Unit names are seeded from CLDR once per locale and hand-edited since; each\n\
         `locales/<tag>.toml` records which release it was seeded from.\n\n",
    );

    out.push_str("## Units\n\n");
    out.push_str(
        "Sizes are given against each quantity's reference unit. Temperature is affine,\n",
    );
    out.push_str("so it has no ratio.\n\n");
    out.push_str("| Identifier | Quantity | Size |\n|---|---|---|\n");
    for unit in Unit::all() {
        let quantity = unit.physical_quantity();
        let size = if quantity == PhysicalQuantity::Temperature {
            "—".to_string()
        } else {
            let reference = reference_unit(quantity);
            let factor = Unit::convert(1.0, unit, reference).expect("same quantity");
            format!("{factor} {}", reference.id())
        };
        writeln!(out, "| `{}` | {quantity:?} | {size} |", unit.id()).unwrap();
    }

    out.push_str("\n## Preferred units by system\n\n");
    out.push_str("Largest first; a value is shown in the first unit it reaches a whole one of,\n");
    out.push_str("falling back to the last. A region gets its official system: only the\n");
    out.push_str("United States is US customary, every other region is metric, and `-u-ms-`\n");
    out.push_str("selects a system outright. Time has one list, under Metric.\n\n");
    out.push_str("| System | Quantity | Order |\n|---|---|---|\n");
    for (system, quantity, rows) in PREFERENCES {
        let order = reference::order(rows, false);
        writeln!(out, "| {system:?} | {quantity:?} | {order} |").unwrap();
    }

    out.push_str("\n## Preferred units by region\n\n");
    out.push_str("A region's own rows, overriding its official system's for that quantity\n");
    out.push_str("only. Thresholds are the amount of the unit a value must reach; none is\n");
    out.push_str("stated by any source (`research/best-units-by-region.md` §7.1).\n\n");
    out.push_str("| Region | Quantity | Order |\n|---|---|---|\n");
    for (region, quantity, rows) in REGION_PREFERENCES {
        let order = reference::order(rows, true);
        writeln!(out, "| {region} | {quantity:?} | {order} |").unwrap();
    }

    out.push_str("\n## Preferred units of the legacy locale\n\n");
    out.push_str("What an untagged recipe is fitted with: `units.toml`'s `best` lists and\n");
    out.push_str("fraction config, frozen, for the system the quantity was written in\n");
    out.push_str("(ADR 7). Bundled's \"imperial\" is US customary.\n\n");
    out.push_str("| System | Quantity | Order |\n|---|---|---|\n");
    for (system, quantity, rows) in LEGACY_PREFERENCES {
        let order = reference::order(rows, true);
        writeln!(out, "| {system:?} | {quantity:?} | {order} |").unwrap();
    }

    out
}

#[cfg(feature = "bundled_units")]
#[test]
fn the_committed_reference_is_current() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/docs/units.md");
    let rendered = render_units_doc();

    if std::env::var_os("UPDATE_UNITS_DOC").is_some() {
        std::fs::write(path, &rendered).expect("writable");
        return;
    }

    let committed = std::fs::read_to_string(path).unwrap_or_default();
    assert_eq!(
        committed, rendered,
        "docs/units.md is stale; rerun with UPDATE_UNITS_DOC=1"
    );
}
