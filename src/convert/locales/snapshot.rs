//! An exhaustive, machine-oriented snapshot of everything the naming and preference layers decide, so that they can
//! be refactored without the data changing by accident.
//!
//! `locales.snapshot` holds every decision, locale by locale and then what belongs to no single locale. The test
//! fails when the committed copy differs; `UPDATE_SNAPSHOT=1 cargo test` rewrites it, and the diff is the review.
//! The `show-locale-as-md` pages show the same decisions to a person; that each kind of page renders is
//! `reference.rs`'s own test.
//!
//! What a rule implies is not repeated here: an identifier resolving to itself, an unnamed unit written by its
//! identifier, a long form with its number dropped in. Each such rule has a unit test in
//! its module, and pinning its consequences per locale would only multiply the diff when the rule changed.

use std::collections::HashSet;
use std::fmt::Write;

use icu_locale_core::subtags::{region, Region};

use crate::convert::locales::legacy::{legacy_locale, LEGACY_PREFERENCES};
use crate::convert::locales::locale::Locale;
use crate::convert::locales::plural;
use crate::convert::locales::preference::{
    best_amount, best_unit, official_system, sourced_rows_for, Audience, Row, System, Units,
    PREFERENCES, REGION_PREFERENCES,
};
use crate::convert::locales::tag::LocaleTag;
use crate::convert::locales::vendored::{
    names_reviewed, tag_for, vendored_locale, vendored_tags, PARENT_LOCALES,
};
use crate::convert::units::{PhysicalQuantity, TemperatureUnit, Unit};

const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/src/convert/locales/locales.snapshot"
);

const HEADER: &str = "# Generated by src/convert/locales/snapshot.rs. Do not edit: run\n\
                      # UPDATE_SNAPSHOT=1 cargo test to refresh. Every line is a decision\n\
                      # the naming or preference layer makes; a diff here is a behaviour\n\
                      # change.\n";

/// Regions whose official system is worth pinning: the one exception, the
/// territories CLDR files under other systems, and a spread of metric ones.
const REGIONS: [Region; 12] = [
    region!("US"),
    region!("GB"),
    region!("LR"),
    region!("MM"),
    region!("001"),
    region!("AU"),
    region!("CA"),
    region!("DE"),
    region!("FR"),
    region!("IN"),
    region!("JP"),
    region!("MX"),
];

/// Magnitudes per physical quantity, in the unit named, straddling every threshold a row sets: the spoons, cups and
/// decilitre below 300 ml, the pint and the kilogram and pound around 500, the decagram and libra at 5 and 125 g.
/// Which unit is best depends on the magnitude alone, so one input unit per quantity is enough.
#[rustfmt::skip]
const SWEEP: [(&str, &[f64]); 5] = [
    ("milliliter", &[0.25, 0.5, 1.0, 2.5, 5.0, 10.0, 15.0, 20.0, 30.0, 50.0, 60.0, 100.0, 150.0, 250.0, 300.0, 500.0, 600.0, 1000.0, 2500.0]),
    ("gram", &[0.5, 1.0, 5.0, 10.0, 28.0, 100.0, 125.0, 250.0, 450.0, 500.0, 1000.0, 2500.0]),
    ("millimeter", &[0.5, 1.0, 5.0, 10.0, 25.4, 100.0, 254.0, 304.8, 1000.0, 2000.0]),
    ("second", &[0.5, 1.0, 30.0, 59.0, 60.0, 90.0, 3599.0, 3600.0, 5400.0, 86400.0, 172800.0]),
    ("celsius", &[-18.0, 0.0, 0.5, 1.0, 100.0, 180.0, 350.0]),
];

fn sweep() -> impl Iterator<Item = (Unit, f64)> {
    SWEEP.iter().flat_map(|(id, values)| {
        let unit = Unit::from_id(id).expect("a unit");
        values.iter().map(move |value| (unit, *value))
    })
}

/// Amounts that exercise the fraction rows: a third, a half, three quarters,
/// a near-whole, wholes, and odd amounts that fit no fraction of the first
/// unit they reach.
const AMOUNT_VALUES: [f64; 8] = [0.3, 0.5, 0.75, 1.1, 3.0, 7.0, 100.0, 2500.0];
const AMOUNT_UNITS: [&str; 6] = [
    "milliliter",
    "gram",
    "us cup",
    "us teaspoon",
    "imperial pint",
    "celsius",
];

const QUANTITIES: [PhysicalQuantity; 5] = [
    PhysicalQuantity::Volume,
    PhysicalQuantity::Mass,
    PhysicalQuantity::Length,
    PhysicalQuantity::Temperature,
    PhysicalQuantity::Time,
];

const AUDIENCES: [Audience; 7] = [
    Audience::system(System::Metric),
    Audience::system(System::UsCustomary),
    Audience::system(System::Imperial),
    Audience::region(region!("US")),
    Audience::region(region!("GB")),
    Audience::legacy(System::Metric),
    Audience::legacy(System::UsCustomary),
];

/// The three systems, two plain regions, and every region with rows of its
/// own, so a new region row is pinned the day it is added.
fn audiences() -> Vec<Audience> {
    let mut audiences: Vec<Audience> = AUDIENCES.to_vec();
    for (region, _, _) in REGION_PREFERENCES {
        let audience = Audience::region(*region);
        if !audiences.contains(&audience) {
            audiences.push(audience);
        }
    }
    audiences
}

/// Every preference row, under the key the snapshot files it by: the system, `region:SE`, or `legacy:Metric`.
fn all_rows() -> impl Iterator<Item = (String, PhysicalQuantity, &'static Row)> {
    let system = PREFERENCES
        .iter()
        .flat_map(|(s, q, rows)| rows.iter().map(move |row| (format!("{s:?}"), *q, row)));
    let region = REGION_PREFERENCES
        .iter()
        .flat_map(|(r, q, rows)| rows.iter().map(move |row| (format!("region:{r}"), *q, row)));
    let legacy = LEGACY_PREFERENCES.iter().flat_map(|(s, q, rows)| {
        rows.iter()
            .map(move |row| (format!("legacy:{s:?}"), *q, row))
    });
    system.chain(region).chain(legacy)
}

fn fractions_suffix(row: &Row) -> String {
    let fractions = match row.fractions {
        Some(den) => format!(" fractions /{den}"),
        None => String::new(),
    };
    if row.or_decimal {
        format!("{fractions} or decimal")
    } else {
        fractions
    }
}

fn audience_name(audience: Audience) -> String {
    let units = match audience.units {
        Units::System(system) => format!("system:{system:?}"),
        Units::Region(region) => format!("region:{region}"),
        Units::Legacy(system) => format!("legacy:{system:?}"),
    };
    match audience.temperature {
        Some(unit) => format!("{units}+mu:{unit:?}"),
        None => units,
    }
}

fn render_decisions(out: &mut String, tag: &str, locale: &Locale) {
    let mut inputs: Vec<(String, &'static str)> = Unit::all()
        .flat_map(|unit| {
            locale
                .names(unit)
                .into_iter()
                .flat_map(|names| names.symbol.iter().chain(&names.aliases).cloned())
                .map(move |s| (s, unit.id()))
        })
        .collect();
    inputs.sort();
    inputs.dedup();
    for (input, id) in inputs {
        assert_eq!(locale.resolve(&input), Unit::from_id(id), "{tag} '{input}'");
        writeln!(out, "resolve {tag} {input:?} -> {id}").unwrap();
    }
    for unit in Unit::all() {
        if let Some(symbol) = locale.symbol(unit) {
            writeln!(out, "written {tag} {} -> {symbol:?}", unit.id()).unwrap();
        }
    }
    for unit in Unit::all() {
        let Some(names) = locale.names(unit) else {
            continue;
        };
        for (category, pattern) in &names.long {
            writeln!(out, "long {tag} {} {category} -> {pattern:?}", unit.id()).unwrap();
        }
    }
    // the category a number falls in, which picks the pattern above; 0, 12 and 14 are where Finnish and Polish leave
    // the obvious one
    if !locale.plural_rules().is_empty() {
        for value in [1.0, 2.0, 5.0, 22.0, 1.5, 0.0, 12.0, 14.0] {
            let number = format!("{value}");
            let category = plural::category(locale.plural_rules(), &number);
            writeln!(out, "plural {tag} {number} -> {category}").unwrap();
        }
    }
}

/// Every locale is here, reviewed or not, so that a name cannot drift before someone reviews the locale and confirms
/// the drifted name as CLDR's.
fn snapshot() -> String {
    let mut out = String::from(HEADER);
    render_decisions(&mut out, "legacy", &legacy_locale());
    let mut tags: Vec<&str> = vendored_tags().collect();
    tags.sort_unstable();
    for tag in &tags {
        render_decisions(&mut out, tag, &vendored_locale(tag).expect("vendored"));
    }
    render_derived(&mut out, &tags);
    out
}

/// What is keyed by tag, region or system rather than by a language's names,
/// and so belongs to no single locale.
fn render_derived(out: &mut String, tags: &[&str]) {
    let mut probes: Vec<String> = tags.iter().map(|t| (*t).to_string()).collect();
    probes.extend(PARENT_LOCALES.iter().map(|(child, _)| child.to_string()));
    probes.extend(
        [
            "en-US",
            "de-AT",
            "de-CH",
            "fr-CA",
            "fr-FR",
            "sv-FI",
            "zh-Hans-CN",
            "und",
            "sw-KE",
        ]
        .map(str::to_string),
    );
    probes.sort();
    probes.dedup();
    for probe in probes {
        let reached = LocaleTag::parse(&probe)
            .ok()
            .and_then(|tag| tag_for(&tag))
            .unwrap_or("none");
        writeln!(out, "fallback {probe} -> {reached}").unwrap();
    }

    for tag in tags {
        writeln!(out, "reviewed {tag} -> {}", names_reviewed(tag)).unwrap();
    }
    for region in REGIONS {
        writeln!(
            out,
            "official-system {region} -> {:?}",
            official_system(region)
        )
        .unwrap();
    }
    for (key, quantity, row) in all_rows() {
        writeln!(
            out,
            "preference {key} {quantity:?} {} >= {}{}",
            row.unit.id(),
            row.at_least,
            fractions_suffix(row)
        )
        .unwrap();
    }
    // `-u-mu-` overrides temperature only: both directions, the other quantities as witnesses that nothing else moves
    let overrides = [
        Audience::region(region!("CA")).with_temperature(TemperatureUnit::Fahrenheit),
        Audience::system(System::UsCustomary).with_temperature(TemperatureUnit::Celsius),
    ];
    // which rule chose the rows: the override for temperature, a region's own rows, the shared time list, the system
    for audience in audiences().into_iter().chain(overrides) {
        for quantity in QUANTITIES {
            let (source, _) = sourced_rows_for(audience, quantity);
            writeln!(
                out,
                "source {} {quantity:?} -> {source}",
                audience_name(audience)
            )
            .unwrap();
        }
    }
    for audience in audiences().into_iter().chain(overrides) {
        for (unit, value) in sweep() {
            let chosen = best_unit(value, unit, audience);
            writeln!(
                out,
                "best {} {value} {} -> {}",
                audience_name(audience),
                unit.id(),
                chosen.id()
            )
            .unwrap();
        }
    }
    // what is written, fraction and unit together, for the amounts that
    // exercise the fraction rows
    let amount_units = AMOUNT_UNITS.map(|id| Unit::from_id(id).expect("a unit"));
    for audience in audiences() {
        for unit in amount_units {
            for value in AMOUNT_VALUES {
                let (amount, chosen) = best_amount(value, unit, audience);
                writeln!(
                    out,
                    "amount {} {value} {} -> {amount} {}",
                    audience_name(audience),
                    unit.id(),
                    chosen.id()
                )
                .unwrap();
            }
        }
    }
}

/// Every unit a preference row can choose is chosen somewhere in the grid.
///
/// Rows are read largest-first and the first whose threshold is met wins, so
/// a row placed below one that always wins is dead; this is what catches it.
/// A unit in no row is unreachable by construction, so adding samples cannot
/// "reach" one -- the lever is the row, not the value.
#[test]
fn the_samples_reach_every_unit_a_row_can_choose() {
    let reachable: HashSet<Unit> = all_rows().map(|(_, _, row)| row.unit).collect();

    let mut chosen: HashSet<Unit> = HashSet::new();
    for audience in audiences() {
        for (unit, value) in sweep() {
            chosen.insert(best_unit(value, unit, audience));
        }
    }

    let unreached: Vec<&str> = {
        let mut v: Vec<&str> = reachable.difference(&chosen).map(|u| u.id()).collect();
        v.sort_unstable();
        v
    };
    assert!(
        unreached.is_empty(),
        "a preference row can choose these and no sample does, so the grid \
         never exercises them: {unreached:?}. Add a magnitude to SWEEP in the \
         band the row covers."
    );
}

/// Writes `body` to `path` under `UPDATE_SNAPSHOT`; otherwise says where the committed copy first differs.
fn pin(path: &str, body: &str) -> Result<(), String> {
    if std::env::var_os("UPDATE_SNAPSHOT").is_some() {
        std::fs::write(path, body).expect("writable");
        return Ok(());
    }
    let committed = std::fs::read_to_string(path).unwrap_or_default();
    if committed == body {
        return Ok(());
    }
    // a full assert_eq! would print two multi-hundred-line strings
    Err(committed
        .lines()
        .zip(body.lines())
        .position(|(a, b)| a != b)
        .map_or_else(|| "length".to_string(), |i| format!("line {}", i + 1)))
}

#[test]
fn the_committed_snapshots_are_current() {
    if let Err(at) = pin(PATH, &snapshot()) {
        panic!(
            "src/convert/locales/locales.snapshot is stale at {at}; rerun with UPDATE_SNAPSHOT=1"
        );
    }
}
